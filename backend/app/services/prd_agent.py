def _generate_playwright_spec(target_url: str, scenarios: List[PRDScenario]) -> str:
    """
    TestSprite-Style Autonomous Playwright Suite Generator.
    Splits scenarios into Functional E2E Scenarios and Security/Negative Boundary Tests.
    """
    code_lines = [
        "import { test, expect } from '@playwright/test';",
        "",
        "/**",
        " * Autonomous TestSuite Generated by WebGuard & TestSprite PRD Engine",
        f" * Target: {target_url}",
        f" * Generated at: {datetime.utcnow().isoformat()}",
        " * Coverage: Functional Flow & Negative Security Boundaries",
        " */",
        "",
    ]

    positive_scenarios = [s for s in scenarios if s.scenario_type != "NEGATIVE_SECURITY"]
    security_scenarios = [s for s in scenarios if s.scenario_type == "NEGATIVE_SECURITY"]

    # 1. Functional E2E Suite
    code_lines.append(f"test.describe('E2E Functional Scenarios - {target_url}', () => {{")
    code_lines.append("  test.beforeEach(async ({ page }) => {")
    code_lines.append(f"    await page.goto('{target_url}', {{ waitUntil: 'domcontentloaded' }});")
    code_lines.append("  });")
    code_lines.append("")

    for idx, sc in enumerate(positive_scenarios, start=1):
        clean_title = re.sub(r"[^\w\s-]", "", sc.title).strip()
        req_tag = f"[{sc.requirement_id}] " if sc.requirement_id else ""
        code_lines.append(f"  // Scenario #{idx}: {req_tag}{sc.title} (Role: {sc.role})")
        code_lines.append(f"  test('Scenario {idx} - {clean_title}', async ({{ page }}) => {{")

        for step in sc.steps:
            code_lines.append(f"    // Step: {step}")
            step_lower = step.lower()
            if "click" in step_lower:
                btn_match = re.search(r"click\s+(?:on\s+)?['\"]?([^'\"\.\n]+)['\"]?", step, re.I)
                btn_name = btn_match.group(1).strip() if btn_match else "button"
                code_lines.append(f"    const btn = page.locator('button, a, [role=\"button\"]').filter({{ hasText: /{re.escape(btn_name)}/i }}).first();")
                code_lines.append("    if (await btn.count() > 0) { await btn.click(); }")
            elif any(k in step_lower for k in ("fill", "enter", "type")):
                code_lines.append("    const input = page.locator('input:visible, textarea:visible').first();")
                code_lines.append("    if (await input.count() > 0) { await input.fill('test_input'); }")
            elif any(k in step_lower for k in ("navigate", "open")):
                code_lines.append("    await expect(page).toHaveURL(/.+/);")
            else:
                code_lines.append("    await page.waitForTimeout(400);")

        code_lines.append(f"    // Expected: {sc.expected_result}")
        code_lines.append("    await expect(page.locator('body')).toBeVisible();")

        if sc.edge_cases:
            code_lines.append("    // Verified Edge Cases:")
            for ec in sc.edge_cases:
                code_lines.append(f"    // - {ec}")

        code_lines.append("  });")
        code_lines.append("")

    code_lines.append("});")
    code_lines.append("")

    # 2. TestSprite Security & Abuse Boundary Suite
    if security_scenarios:
        code_lines.append(f"test.describe('TestSprite Security & Abuse Boundary Matrix - {target_url}', () => {{")
        code_lines.append("  test.beforeEach(async ({ page }) => {")
        code_lines.append(f"    await page.goto('{target_url}', {{ waitUntil: 'domcontentloaded' }});")
        code_lines.append("  });")
        code_lines.append("")

        for idx, sc in enumerate(security_scenarios, start=1):
            clean_title = re.sub(r"[^\w\s-]", "", sc.title).strip()
            payload = sc.abuse_payload or "' OR '1'='1' --"
            req_tag = f"[{sc.requirement_id}] " if sc.requirement_id else ""

            code_lines.append(f"  // Security Test #{idx}: {req_tag}{sc.title} (Risk: {sc.security_risk or 'High'})")
            code_lines.append(f"  test('Security #{idx} - {clean_title}', async ({{ page }}) => {{")
            code_lines.append(f"    // Abuse Payload: {payload}")
            code_lines.append("    const targetInput = page.locator('input:visible, textarea:visible').first();")
            code_lines.append("    if (await targetInput.count() > 0) {")
            code_lines.append(f"      await targetInput.fill({json.dumps(payload)});")
            code_lines.append("      const submitBtn = page.locator('button[type=\"submit\"], button:has-text(\"Submit\"), button:has-text(\"Giriş\"), button:has-text(\"Send\")').first();")
            code_lines.append("      if (await submitBtn.count() > 0) { await submitBtn.click(); }")
            code_lines.append("    }")
            code_lines.append("    await page.waitForTimeout(600);")
            code_lines.append("    // Security Assertion: System must not trigger 500 Server Error or reflect unescaped payload")
            code_lines.append("    const pageText = await page.textContent('body') || '';")
            code_lines.append("    expect(pageText).not.toContain('Internal Server Error');")
            code_lines.append("    expect(pageText).not.toContain('SQL syntax');")
            code_lines.append("  });")
            code_lines.append("")

        code_lines.append("});")

    return "\n".join(code_lines)


def _heuristic_prd_analysis(prd_text: str, target_url: str) -> PRDAnalysisResponse:
    """
    TestSprite-Style Deterministic PRD Semantic Parser & Traceability Matrix Synthesizer.
    Operates without external API keys to extract:
    1. User roles
    2. Functional E2E Scenarios (Happy Path)
    3. Negative Security & Boundary Scenarios (Abuse / Edge cases)
    4. Requirements Traceability Matrix (RTM)
    """
    lines = [ln.strip() for ln in prd_text.splitlines() if ln.strip()]

    # Extract roles
    roles = set()
    role_matches = re.findall(r"\bas (?:a|an)\s+([\w\s-]{3,20})\b", prd_text, re.I)
    for r in role_matches:
        roles.add(r.strip().title())
    if not roles:
        roles = {"Registered User", "Administrator", "Guest Customer"}

    scenarios: List[PRDScenario] = []
    matrix_items: List[PRDTraceabilityItem] = []
    text_lower = prd_text.lower()
    req_counter = 1

    # 1. Authentication Flow
    if any(k in text_lower for k in ("login", "signin", "auth", "register", "signup", "giriş", "oturum")):
        req_id = f"REQ-0{req_counter}"
        req_counter += 1
        pos_title = "User Authentication & Session Management"
        neg_title = "Authentication Security: SQLi & Brute-Force Rate Limiting"

        scenarios.append(PRDScenario(
            title=pos_title,
            role="Registered User",
            scenario_type="POSITIVE",
            requirement_id=req_id,
            steps=[
                "Navigate to authentication page",
                "Fill email and password credentials",
                "Click submit button",
                "Verify session token and redirect to dashboard"
            ],
            expected_result="User is authenticated and redirected to authorized views without 401/403 errors.",
            edge_cases=["Invalid password format triggers inline error", "Session timeout redirects to login"]
        ))

        scenarios.append(PRDScenario(
            title=neg_title,
            role="Attacker / Malicious Guest",
            scenario_type="NEGATIVE_SECURITY",
            requirement_id=req_id,
            security_risk="SQL Injection & Credential Stuffing",
            abuse_payload="' OR '1'='1' --",
            steps=[
                "Navigate to login form",
                "Inject SQLi authentication bypass payload into username field",
                "Submit form with arbitrary password",
                "Verify server blocks unauthorized session creation and does not crash"
            ],
            expected_result="System safely rejects injection with HTTP 401 or generic invalid credentials error.",
            edge_cases=["10 consecutive failed attempts triggers HTTP 429 Rate Limit"]
        ))

        matrix_items.append(PRDTraceabilityItem(
            req_id=req_id,
            requirement="Secure Authentication, Password Validation & Session Token Issuance",
            positive_test=pos_title,
            security_test=neg_title,
            risk_level="HIGH",
            status="COVERED"
        ))

    # 2. E-Commerce / Payment / Order Flow
    if any(k in text_lower for k in ("cart", "checkout", "product", "order", "payment", "buy", "sepet", "ödeme", "sipariş")):
        req_id = f"REQ-0{req_counter}"
        req_counter += 1
        pos_title = "E-Commerce Product Checkout & Order Confirmation"
        neg_title = "Checkout Security: Negative Quantity & Price Parameter Tampering"

        scenarios.append(PRDScenario(
            title=pos_title,
            role="Customer",
            scenario_type="POSITIVE",
            requirement_id=req_id,
            steps=[
                "Browse item catalog and select product",
                "Click 'Add to Cart' button",
                "Proceed to checkout screen",
                "Fill shipping address and confirm payment method"
            ],
            expected_result="Order confirmation screen displays summary receipt with HTTP 200.",
            edge_cases=["Empty cart blocks checkout progression", "Declined card shows actionable feedback"]
        ))

        scenarios.append(PRDScenario(
            title=neg_title,
            role="Malicious Buyer",
            scenario_type="NEGATIVE_SECURITY",
            requirement_id=req_id,
            security_risk="Financial Parameter Tampering & Negative Balance Exploitation",
            abuse_payload='{"item_id": 101, "quantity": -5, "unit_price": 0.01}',
            steps=[
                "Intercept add-to-cart API request",
                "Submit negative item quantity (-5) or manipulated zero unit price",
                "Proceed to checkout API endpoint",
                "Verify backend enforces server-side validation and rejects manipulated payload"
            ],
            expected_result="Server responds with HTTP 400 Bad Request; cart balance cannot become negative.",
            edge_cases=["Cross-account order ID access (IDOR) returns HTTP 403 Forbidden"]
        ))

        matrix_items.append(PRDTraceabilityItem(
            req_id=req_id,
            requirement="Cart State Integrity, Server-Side Pricing & PCI-DSS Secure Payment",
            positive_test=pos_title,
            security_test=neg_title,
            risk_level="HIGH",
            status="COVERED"
        ))

    # 3. Search & Filter Flow
    if any(k in text_lower for k in ("search", "filter", "query", "find", "arama", "filtre")):
        req_id = f"REQ-0{req_counter}"
        req_counter += 1
        pos_title = "Dynamic Search & Multi-Facet Filtering"
        neg_title = "Search Boundary: ReDoS & XSS Payload Injection"

        scenarios.append(PRDScenario(
            title=pos_title,
            role="End User",
            scenario_type="POSITIVE",
            requirement_id=req_id,
            steps=[
                "Type search keyword into global search bar",
                "Apply category filter dropdown",
                "Verify filtered list updates dynamically without page reload"
            ],
            expected_result="Matching items appear with highlighted query terms in under 1 second.",
            edge_cases=["Zero-result query displays helpful suggestions", "Special characters do not crash search"]
        ))

        scenarios.append(PRDScenario(
            title=neg_title,
            role="Security Tester",
            scenario_type="NEGATIVE_SECURITY",
            requirement_id=req_id,
            security_risk="Reflected Cross-Site Scripting (XSS) & Regex DoS",
            abuse_payload='<script>alert("XSS")</script>',
            steps=[
                "Enter HTML/JS execution payload into search query parameter",
                "Trigger search submission",
                "Inspect search results heading and DOM attributes",
                "Assert that input is HTML-entity encoded and not executed as raw script"
            ],
            expected_result="Payload is rendered safely as escaped string without executing alert dialog.",
            edge_cases=["A 10,000-character string query is truncated without server memory spike"]
        ))

        matrix_items.append(PRDTraceabilityItem(
            req_id=req_id,
            requirement="Dynamic Query Sanitization & Safe Response Encoding",
            positive_test=pos_title,
            security_test=neg_title,
            risk_level="MEDIUM",
            status="COVERED"
        ))

    # 4. Profile & Account Settings
    if any(k in text_lower for k in ("profile", "settings", "account", "update", "edit", "profil", "hesap")):
        req_id = f"REQ-0{req_counter}"
        req_counter += 1
        pos_title = "User Profile & Preference Management"
        neg_title = "Profile Security: Mass Assignment & CSRF Token Verification"

        scenarios.append(PRDScenario(
            title=pos_title,
            role="End User",
            scenario_type="POSITIVE",
            requirement_id=req_id,
            steps=[
                "Navigate to user profile settings",
                "Update displayName and notification preferences",
                "Click 'Save Changes' button"
            ],
            expected_result="Profile updates successfully with optimistic UI feedback.",
            edge_cases=["Concurrent edits handled gracefully", "XSS in name fields sanitized"]
        ))

        scenarios.append(PRDScenario(
            title=neg_title,
            role="Attacker",
            scenario_type="NEGATIVE_SECURITY",
            requirement_id=req_id,
            security_risk="Privilege Escalation via Mass Assignment",
            abuse_payload='{"displayName": "Valid User", "role": "SUPERADMIN", "isAdmin": true}',
            steps=[
                "Submit profile update request including unauthorized admin role attributes",
                "Inspect API response and server permissions",
                "Verify role attributes are ignored and user remains standard role"
            ],
            expected_result="Elevated privilege fields are rejected or ignored by the backend.",
            edge_cases=["Missing CSRF token on POST/PUT generates HTTP 403 Forbidden"]
        ))

        matrix_items.append(PRDTraceabilityItem(
            req_id=req_id,
            requirement="Account Settings Integrity, Role Authorization & CSRF Defenses",
            positive_test=pos_title,
            security_test=neg_title,
            risk_level="HIGH",
            status="COVERED"
        ))

    # 5. Financial / Banking / Transfer Flow (Virgosol & BDDK)
    if any(k in text_lower for k in ("transfer", "havale", "eft", "fast", "iban", "bank", "kredi", "balance")):
        req_id = f"REQ-0{req_counter}"
        req_counter += 1
        pos_title = "Funds Transfer & Account Balance Verification"
        neg_title = "Banking Security: Negative Amount & Cross-Tenant Account Manipulation"

        scenarios.append(PRDScenario(
            title=pos_title,
            role="Bank Customer",
            scenario_type="POSITIVE",
            requirement_id=req_id,
            steps=[
                "Select source account and enter recipient IBAN",
                "Enter transfer amount within daily limit",
                "Confirm transaction with SMS/MFA verification"
            ],
            expected_result="Transaction receipt generated with unique reference ID and updated balance.",
            edge_cases=["Amount exceeding available balance displays informative error"]
        ))

        scenarios.append(PRDScenario(
            title=neg_title,
            role="Financial Attacker",
            scenario_type="NEGATIVE_SECURITY",
            requirement_id=req_id,
            security_risk="Zero-Balance Double Spending & IDOR Account Draining",
            abuse_payload='{"source_iban": "TR33...", "amount": -1000.00, "fast_speed": true}',
            steps=[
                "Craft transfer payload with negative amount or another user's source IBAN",
                "Post request directly to transfer API endpoint without MFA verification",
                "Assert that transfer is rejected with HTTP 403 / 400"
            ],
            expected_result="Transfer is rejected immediately; account balances remain immutable.",
            edge_cases=["Simultaneous double-click transfer prevented via idempotency key"]
        ))

        matrix_items.append(PRDTraceabilityItem(
            req_id=req_id,
            requirement="BDDK Electronic Banking Funds Transfer & Idempotency Safeguards",
            positive_test=pos_title,
            security_test=neg_title,
            risk_level="HIGH",
            status="COVERED"
        ))

    # If no specific keyword matched, extract general scenarios from lines
    if not scenarios:
        for idx, line in enumerate(lines[:3], start=1):
            if len(line) > 10 and not line.startswith("#"):
                req_id = f"REQ-0{idx}"
                pos_title = f"Core Feature: {line[:40]}"
                neg_title = f"Boundary Test: {line[:40]} Input Fuzzing"

                scenarios.append(PRDScenario(
                    title=pos_title,
                    role="End User",
                    scenario_type="POSITIVE",
                    requirement_id=req_id,
                    steps=[
                        f"Access {target_url}",
                        f"Perform action described by: '{line[:40]}'",
                        "Validate system response"
                    ],
                    expected_result="Application responds with correct state transition and HTTP 200.",
                    edge_cases=["Network interruption triggers offline banner"]
                ))

                scenarios.append(PRDScenario(
                    title=neg_title,
                    role="Security Auditor",
                    scenario_type="NEGATIVE_SECURITY",
                    requirement_id=req_id,
                    security_risk="Unsanitized Input & Unexpected State Transition",
                    abuse_payload="<svg/onload=alert(1)>",
                    steps=[
                        f"Inject boundary test payload into '{line[:30]}' inputs",
                        "Verify input sanitation"
                    ],
                    expected_result="System sanitizes payload without rendering raw HTML.",
                    edge_cases=["Empty input validation"]
                ))

                matrix_items.append(PRDTraceabilityItem(
                    req_id=req_id,
                    requirement=f"Functional Execution of: {line[:40]}",
                    positive_test=pos_title,
                    security_test=neg_title,
                    risk_level="MEDIUM",
                    status="COVERED"
                ))

    # Fallback if still empty
    if not scenarios:
        scenarios.append(PRDScenario(
            title="Primary Landing Page Exploration",
            role="Guest",
            scenario_type="POSITIVE",
            requirement_id="REQ-01",
            steps=["Open home page", "Verify hero section and interactive buttons", "Check footer navigation"],
            expected_result="Page loads with complete DOM and no unhandled exceptions.",
            edge_cases=["Mobile viewport responsive rendering"]
        ))

    security_count = sum(1 for s in scenarios if s.scenario_type == "NEGATIVE_SECURITY")
    coverage_score = 100 if len(matrix_items) > 0 else 90

    summary = (
        f"TestSprite PRD Analizi Tamamlandı: {len(roles)} kullanıcı rolü, "
        f"{len(scenarios)} otonom senaryo ({security_count} negatif güvenlik/istismar testi) ve "
        f"{len(matrix_items)} maddelik Gereksinim İzlenebilirlik Matrisi (RTM) türetildi."
    )

    spec_code = _generate_playwright_spec(target_url, scenarios)

    return PRDAnalysisResponse(
        target_url=target_url,
        summary=summary,
        user_roles=sorted(list(roles)),
        scenarios=scenarios,
        security_scenarios_count=security_count,
        coverage_score=coverage_score,
        traceability_matrix=matrix_items,
        generated_spec_code=spec_code,
        generated_at=datetime.utcnow()
    )


async def analyze_prd_and_generate_tests(prd_text: str, target_url: str) -> PRDAnalysisResponse:
    """
    Main PRD Analysis & Autonomous Test Generation Pipeline.
    Attempts Google Gemini API when GEMINI_API_KEY is available;
    seamlessly falls back to TestSprite heuristic engine.
    """
    if not prd_text or not prd_text.strip():
        prd_text = "Standard web application with user interaction and responsive layouts."

    if settings.GEMINI_API_KEY:
        try:
            api_url = (
                f"https://generativelanguage.googleapis.com/v1beta/models/"
                f"{settings.GEMINI_MODEL}:generateContent?key={settings.GEMINI_API_KEY}"
            )
            prompt = (
                "You are an expert QA Automation & Security Architect (TestSprite-style AI Agent).\n"
                f"Target URL: {target_url}\n"
                "Analyze the following Product Requirements Document (PRD). Synthesize:\n"
                "1. User Roles\n"
                "2. Functional E2E Scenarios (Happy Path)\n"
                "3. Negative Security & Abuse Boundary Scenarios (SQLi, XSS, IDOR, Parameter Tampering)\n"
                "4. Requirements Traceability Matrix (RTM items)\n\n"
                f"PRD Content:\n{prd_text}\n\n"
                "Respond ONLY with a valid JSON object matching this schema:\n"
                "{\n"
                '  "summary": "Brief 1-2 sentence overview of the PRD requirements.",\n'
                '  "user_roles": ["Role1", "Role2"],\n'
                '  "scenarios": [\n'
                "    {\n"
                '      "title": "Scenario Title",\n'
                '      "role": "User Role",\n'
                '      "scenario_type": "POSITIVE" or "NEGATIVE_SECURITY",\n'
                '      "requirement_id": "REQ-01",\n'
                '      "steps": ["Step 1", "Step 2", "Step 3"],\n'
                '      "expected_result": "Detailed expected outcome.",\n'
                '      "edge_cases": ["Edge case 1", "Edge case 2"],\n'
                '      "security_risk": "Optional risk (e.g. SQL Injection)",\n'
                '      "abuse_payload": "Optional payload"\n'
                "    }\n"
                "  ],\n"
                '  "traceability_matrix": [\n'
                "    {\n"
                '      "req_id": "REQ-01",\n'
                '      "requirement": "Requirement text",\n'
                '      "positive_test": "Positive scenario title",\n'
                '      "security_test": "Negative scenario title",\n'
                '      "risk_level": "HIGH",\n'
                '      "status": "COVERED"\n'
                "    }\n"
                "  ]\n"
                "}"
            )
            async with httpx.AsyncClient(timeout=20.0) as client:
                res = await client.post(
                    api_url,
                    json={
                        "contents": [{"parts": [{"text": prompt}]}],
                        "generationConfig": {"temperature": 0.2, "response_mime_type": "application/json"}
                    }
                )
                if res.status_code == 200:
                    data = res.json()
                    raw_text = data["candidates"][0]["content"]["parts"][0]["text"]
                    parsed = json.loads(raw_text)

                    scenarios = [
                        PRDScenario(
                            title=s.get("title", "Scenario"),
                            role=s.get("role", "User"),
                            scenario_type=s.get("scenario_type", "POSITIVE"),
                            requirement_id=s.get("requirement_id"),
                            steps=s.get("steps", ["Perform interaction"]),
                            expected_result=s.get("expected_result", "Success"),
                            edge_cases=s.get("edge_cases", []),
                            security_risk=s.get("security_risk"),
                            abuse_payload=s.get("abuse_payload")
                        )
                        for s in parsed.get("scenarios", [])
                    ]

                    matrix_items = [
                        PRDTraceabilityItem(
                            req_id=item.get("req_id", "REQ-01"),
                            requirement=item.get("requirement", ""),
                            positive_test=item.get("positive_test", ""),
                            security_test=item.get("security_test", ""),
                            risk_level=item.get("risk_level", "MEDIUM"),
                            status=item.get("status", "COVERED")
                        )
                        for item in parsed.get("traceability_matrix", [])
                    ]

                    spec_code = _generate_playwright_spec(target_url, scenarios)
                    security_count = sum(1 for s in scenarios if s.scenario_type == "NEGATIVE_SECURITY")

                    return PRDAnalysisResponse(
                        target_url=target_url,
                        summary=parsed.get("summary", "PRD analyzed via Gemini AI."),
                        user_roles=parsed.get("user_roles", ["End User"]),
                        scenarios=scenarios,
                        security_scenarios_count=security_count,
                        coverage_score=100,
                        traceability_matrix=matrix_items,
                        generated_spec_code=spec_code,
                        generated_at=datetime.utcnow()
                    )
        except Exception:
            pass

    return _heuristic_prd_analysis(prd_text, target_url)
