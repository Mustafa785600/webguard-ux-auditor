class WAFLeakageProbingEngine:
    """
    WAF ve Hata Sızıntısı Direnç Testi Motoru.
    """

    def __init__(self, concurrency: int = 4, timeout_seconds: float = 6.0):
        self.concurrency = concurrency
        self.timeout_seconds = timeout_seconds

    async def audit_waf_and_error_leakage(
        self,
        target_url: str,
        client: Optional[httpx.AsyncClient] = None,
    ) -> Tuple[WAFResilienceReport, List[Finding]]:
        findings: List[Finding] = []
        probe_results: List[WAFProbeResult] = []

        # 1. İlk Temel İstek (WAF Varlığını ve Normal Başlıkları Algılama)
        detected_waf_vendor = "Direct Exposure (No WAF Detected)"
        is_waf_detected = False

        headers = {
            "User-Agent": "WebGuard-WAF-Resilience-Auditor/2.0 (Virgosol-Enterprise)",
            "Accept": "text/html,application/xhtml+xml,application/json,*/*",
        }

        session = client or httpx.AsyncClient(headers=headers, follow_redirects=True, verify=False)
        should_close_session = client is None

        try:
            t0 = time.perf_counter()
            try:
                base_resp = await session.get(target_url, timeout=self.timeout_seconds)
                detected_waf_vendor, is_waf_detected = self._identify_waf(
                    base_resp.headers, base_resp.text, base_resp.status_code, base_resp.cookies
                )
            except Exception:
                pass

            # 2. Sentetik Probların Eşzamanlı Yürütülmesi
            semaphore = asyncio.Semaphore(self.concurrency)

            async def execute_probe(probe_spec: Dict[str, Any]):
                async with semaphore:
                    p_start = time.perf_counter()
                    p_cat = probe_spec["category"]
                    p_name = probe_spec["name"]
                    p_vector = probe_spec["vector"]
                    p_payload = probe_spec["payload"]

                    status_code = 0
                    resp_body = ""
                    matched_waf_name = None

                    try:
                        if p_vector == "Query Param":
                            p_param = probe_spec["param_name"]
                            probe_query = urlencode({p_param: p_payload})
                            delimiter = "&" if "?" in target_url else "?"
                            probe_url = f"{target_url}{delimiter}{probe_query}"
                            resp = await session.get(probe_url, timeout=self.timeout_seconds)
                            status_code = resp.status_code
                            resp_body = resp.text

                        elif p_vector == "HTTP Header":
                            h_name = probe_spec["header_name"]
                            custom_headers = {h_name: p_payload}
                            resp = await session.get(target_url, headers=custom_headers, timeout=self.timeout_seconds)
                            status_code = resp.status_code
                            resp_body = resp.text

                        elif p_vector == "POST Body":
                            resp = await session.post(
                                target_url,
                                content=p_payload,
                                headers={"Content-Type": "application/json"},
                                timeout=self.timeout_seconds,
                            )
                            status_code = resp.status_code
                            resp_body = resp.text

                        # WAF tetiklenmesi kontrolü
                        vendor, waf_flag = self._identify_waf(resp.headers, resp_body, status_code, resp.cookies)
                        if waf_flag:
                            matched_waf_name = vendor

                    except httpx.TimeoutException:
                        status_code = 504
                    except Exception:
                        status_code = 500

                    p_elapsed_ms = round((time.perf_counter() - p_start) * 1000.0, 1)

                    # 3. Yanıtı Sınıflandırma (WAF Blocked vs Clean vs Crash vs Leakage)
                    probe_status, leakage_detail = self._evaluate_response(status_code, resp_body, matched_waf_name)

                    probe_results.append(
                        WAFProbeResult(
                            category=p_cat,
                            probe_name=p_name,
                            target_vector=p_vector,
                            payload_sample=p_payload[:80],
                            status_code=status_code,
                            probe_status=probe_status,
                            detected_leakage=leakage_detail,
                            waf_signature_matched=matched_waf_name,
                            response_time_ms=p_elapsed_ms,
                        )
                    )

            tasks = [execute_probe(p) for p in SAFE_PROBES]
            await asyncio.gather(*tasks, return_exceptions=True)

        finally:
            if should_close_session:
                await session.aclose()

        # 4. İstatistik ve Metriklerin Konsolidasyonu
        total_probes = len(probe_results)
        blocked_count = sum(1 for r in probe_results if r.probe_status == WAFProbeStatus.BLOCKED_BY_WAF)
        clean_count = sum(1 for r in probe_results if r.probe_status == WAFProbeStatus.HANDLED_CLEANLY)
        crashes_500_count = sum(1 for r in probe_results if r.probe_status == WAFProbeStatus.UNHANDLED_500_CRASH)
        leaks_count = sum(1 for r in probe_results if r.probe_status == WAFProbeStatus.STACK_TRACE_LEAK)

        # WAF Dayanıklılık Skoru Hesabı (0-100)
        score = 100
        if not is_waf_detected:
            score -= 15  # WAF eksikliği
        score -= leaks_count * 25  # Her stack trace / db sızıntısı -25 puan
        score -= crashes_500_count * 10  # Her unhandled 500 hatası -10 puan
        waf_protection_score = max(20, min(100, score))

        # 5. Güvenlik ve Uyum Bulguları Üretimi (Findings Formulation)
        if leaks_count > 0:
            leak_samples = [r for r in probe_results if r.probe_status == WAFProbeStatus.STACK_TRACE_LEAK]
            first_leak = leak_samples[0]
            findings.append(
                Finding(
                    id="SEC_WAF_STACK_TRACE_LEAKAGE",
                    category=Category.SECURITY,
                    severity=Severity.CRITICAL,
                    title=f"Kritik Stack Trace ve İç Hata Sızıntısı ({first_leak.detected_leakage})",
                    description=(
                        f"Sunucu sentetik güvenlik problarına ({first_leak.category}) yanıt verirken "
                        f"iç mimariyi ve veritabanı sürücüsünü ifşa eden ayrıntılı hata ekranı döndürdü: "
                        f"{first_leak.detected_leakage}."
                    ),
                    remediation=(
                        "Üretim (production) ortamında 'DEBUG=False' yapın, ayrıntılı hata ayıklayıcıları (Werkzeug, Ignition) kapatın. "
                        "Tüm beklenmedik hataları genel bir exception handler (try-catch middleware) ile yakalayarak "
                        "kullanıcıya yalnızca genel bir hata mesajı (örneğin 'Sistemde beklenmedik bir hata oluştu') döndürün."
                    ),
                    risk_impact=(
                        "Saldırganlar sızan dosya yollarını, veritabanı türünü ve satır numaralarını kullanarak "
                        "doğrudan sıfır-gün (zero-day) veya hedefe yönelik SQLi/RCE açıklarını tetikleyebilir."
                    ),
                    evidence={
                        "leak_technology": first_leak.detected_leakage,
                        "trigger_payload": first_leak.payload_sample,
                        "status_code": first_leak.status_code,
                        "total_leaking_probes": leaks_count,
                    },
                    rca_category=RCACategory.REAL_BUG,
                    team_assignment="Yazılım Geliştirici (Backend / Core API)",
                    root_cause_hypothesis="Web çatısında genel istisna yakalayıcı (global exception handler) bulunmuyor veya debug modu açık unutulmuş.",
                    code_example=(
                        "# FastAPI / Starlette Global Exception Handler Örneği\n"
                        "@app.exception_handler(Exception)\n"
                        "async def global_exception_handler(request: Request, exc: Exception):\n"
                        "    logger.error(f'Internal Server Error: {exc}', exc_info=True)\n"
                        "    return JSONResponse(status_code=500, content={'error': 'İşlem sırasında bir hata oluştu.'})\n"
                    ),
                )
            )

        if crashes_500_count > 0 and leaks_count == 0:
            crashed_probes = [r for r in probe_results if r.probe_status == WAFProbeStatus.UNHANDLED_500_CRASH]
            findings.append(
                Finding(
                    id="SEC_WAF_UNHANDLED_500_CRASH",
                    category=Category.SECURITY,
                    severity=Severity.MEDIUM,
                    title=f"Beklenmedik Girdide İşlenmemiş 500 Çöküşü ({len(crashed_probes)} Prob)",
                    description=(
                        f"Sunucu sentetik girdilerle karşılaştığında HTTP 500 Internal Server Error döndürdü. "
                        f"Stack trace sızmasa da girdilerin sunucu katmanına kadar ulaşıp istisna (exception) fırlattığı gözlemlendi."
                    ),
                    remediation=(
                        "Tüm API ve form girdilerini en dış katmanda (API Gateway / Pydantic / Zod / Request Validator) "
                        "şemaya göre doğrulayın; geçersiz karakter veya tiplerde 500 yerine HTTP 400 Bad Request döndürün."
                    ),
                    risk_impact="İşlenmemiş istisnalar sunucu kaynaklarını (CPU/RAM/DB Connection) tüketerek Hizmet Engelleme (DoS) riskini artırır.",
                    evidence={
                        "crashed_probes_count": len(crashed_probes),
                        "sample_probe": crashed_probes[0].probe_name,
                    },
                    rca_category=RCACategory.REAL_BUG,
                    team_assignment="Yazılım Geliştirici (Backend / API)",
                )
            )

        if not is_waf_detected:
            findings.append(
                Finding(
                    id="SEC_NO_WAF_PROTECTION",
                    category=Category.SECURITY,
                    severity=Severity.LOW,
                    title="Uygulama Seviyesinde WAF (Web Application Firewall) Tespit Edilemedi",
                    description=(
                        "Hedef web uygulaması önünde herhangi bir bulut tabanlı (Cloudflare, AWS WAF, Akamai) "
                        "veya yerel (ModSecurity) güvenlik duvarı tespit edilemedi. İstekler doğrudan kaynak sunucuya ulaşıyor."
                    ),
                    remediation=(
                        "Uygulamanın önüne Cloudflare, AWS WAF veya benzeri bir ters vekil WAF çözümü konumlandırarak "
                        "otomatik bot saldırılarını, DDoS girişimlerini ve yaygın OWASP Top 10 açıklarını ağ kenarında (edge) engelleyin."
                    ),
                    risk_impact="WAF bulunmaması durumunda tüm kötü niyetli bot trafiği doğrudan uygulama sunucusuna yük bindirir.",
                    evidence={"detected_vendor": detected_waf_vendor},
                    rca_category=RCACategory.ENV_ISSUE,
                    team_assignment="DevOps & Sistem Yöneticisi (Infra/SecOps)",
                )
            )

        report = WAFResilienceReport(
            waf_detected=is_waf_detected,
            waf_vendor=detected_waf_vendor,
            waf_protection_score=waf_protection_score,
            total_probes_executed=total_probes,
            probes_blocked_by_waf=blocked_count,
            probes_handled_cleanly=clean_count,
            unhandled_500_crashes=crashes_500_count,
            stack_trace_leaks=leaks_count,
            probe_results=probe_results,
        )

        return report, findings

    def _identify_waf(
        self,
        headers: httpx.Headers,
        body_text: str,
        status_code: int,
        cookies: httpx.Cookies,
    ) -> Tuple[str, bool]:
        """Başlıklar, çerezler ve gövde kalıplarından aktif WAF sağlayıcısını tespit eder."""
        lower_headers = {k.lower(): v.lower() for k, v in headers.items()}
        server_header = lower_headers.get("server", "")

        for sig in WAF_SIGNATURES:
            vendor = sig["vendor"]
            # Başlık eşleşmesi
            for h in sig["headers"]:
                if h in lower_headers:
                    return vendor, True

            # Server başlığı eşleşmesi
            for s in sig["server"]:
                if s in server_header:
                    return vendor, True

            # Çerez eşleşmesi
            for c in sig["cookies"]:
                if any(c in ck for ck in cookies.keys()):
                    return vendor, True

            # Gövde blok metni eşleşmesi (genellikle 403 sayfalarında)
            for b in sig["body"]:
                if b.lower() in body_text.lower():
                    return vendor, True

        return "Direct Exposure (No WAF Detected)", False

    def _evaluate_response(
        self,
        status_code: int,
        body_text: str,
        matched_waf_name: Optional[str],
    ) -> Tuple[WAFProbeStatus, Optional[str]]:
        """Dönen HTTP durum kodu ve gövdeye göre probun akıbetini puanlar."""
        # 1. Önce Kritik Stack Trace / Veritabanı Sızıntısını Tara
        if body_text:
            for leak in LEAKAGE_PATTERNS:
                if leak["regex"].search(body_text):
                    return WAFProbeStatus.STACK_TRACE_LEAK, leak["name"]

        # 2. WAF Tarafından Bloklanma (403 veya 400 ile WAF imzası)
        if status_code in (403, 400) and (matched_waf_name or status_code == 403):
            return WAFProbeStatus.BLOCKED_BY_WAF, None

        # 3. İşlenmemiş 500 / 502 / 504 Çöküşü
        if status_code >= 500:
            return WAFProbeStatus.UNHANDLED_500_CRASH, None

        # 4. Uygulama Tarafından Temizce İşlenme (200, 400, 404, 422)
        return WAFProbeStatus.HANDLED_CLEANLY, None
