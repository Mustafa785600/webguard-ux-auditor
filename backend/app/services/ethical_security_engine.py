class EthicalSecurityEngine:
    """
    Otonom Beyaz Şapkalı Güvenlik ve Siber Dayanıklılık Motoru (White-Hat Red Team).
    Hedef sisteme zarar vermeden WAF etkinliğini, hız sınırı (rate-limiting) tepkisini
    ve açık kapı saldırı yüzeyini canlı problarla denetler.
    """

    @classmethod
    async def audit(
        cls,
        target_url: str,
        client: Optional[httpx.AsyncClient] = None,
    ) -> Tuple[EthicalSecurityReport, List[Finding]]:
        findings: List[Finding] = []
        open_door_probes: List[OpenDoorProbe] = []
        canary_probes: List[WAFCanaryProbe] = []
        key_strengths: List[str] = []
        critical_vulnerabilities: List[str] = []

        # Canlı Kırmızı Takım operasyon duyurusu
        live_hub.record_action(
            label="🛡️ [Etik Hacker Modu] Otonom Beyaz Şapkalı Güvenlik Denetimi Devrede",
            action_type="GATE",
            target="cyber_defense",
            coords={"x": 512, "y": 80}
        )

        close_client = False
        if client is None:
            client = httpx.AsyncClient(timeout=8.0, verify=False, follow_redirects=True)
            close_client = True

        try:
            # ── 1. HAT: WAF VE ÇEVRE GÜVENLİĞİ DENETİMİ ─────────────────────────
            live_hub.record_action(
                label="🛡️ [WAF Savunması] WAF parmak izi ve aktif çevre koruması taranıyor",
                action_type="GATE",
                target="waf_shield",
                coords={"x": 512, "y": 120}
            )

            # Temel istek atıp başlıkları inceleyelim
            base_resp = None
            detected_waf: Optional[str] = None
            try:
                base_resp = await client.get(target_url)
                headers_lower = {k.lower(): v.lower() for k, v in base_resp.headers.items()}
                server_hdr = headers_lower.get("server", "")

                for sig in WAF_SIGNATURES:
                    vendor = sig["vendor"]
                    if any(h in headers_lower for h in sig["headers"]):
                        detected_waf = vendor
                        break
                    if any(s in server_hdr for s in sig["server"]):
                        detected_waf = vendor
                        break
                    body_text = base_resp.text
                    if any(b in body_text for b in sig["body"]):
                        detected_waf = vendor
                        break
            except Exception:
                pass

            if detected_waf:
                key_strengths.append(f"Aktif WAF Güvenlik Kalkanı tespit edildi: {detected_waf}")
                live_hub.record_action(
                    label=f"🛡️ [WAF Tespit Edildi] {detected_waf} devrede, filtreleme canarileri deneniyor",
                    action_type="GATE",
                    target=detected_waf,
                    coords={"x": 512, "y": 140}
                )
            else:
                live_hub.record_action(
                    label="⚠️ [WAF Uyarısı] Ön planda belirgin bir kurumsal WAF parmak izi bulunamadı",
                    action_type="GATE",
                    target="waf_shield",
                    coords={"x": 512, "y": 140}
                )

            # 4 Adet Zararsız Sentetik Canarinin Test Edilmesi
            canaries = [
                ("SQL_INJECTION", "' OR 'webguard'='webguard", "id"),
                ("XSS_REFLECTED", "<webguard-canary-tag>", "q"),
                ("PATH_TRAVERSAL", "..%2F..%2Fwebguard_probe", "file"),
                ("MALFORMED_BODY", "{'webguard': [unclosed", "body"),
            ]

            waf_blocked_count = 0
            for vector, payload, param in canaries:
                probe_url = f"{target_url.rstrip('/')}/?{param}={payload}"
                try:
                    c_resp = await client.get(probe_url, timeout=5.0)
                    is_blocked = c_resp.status_code in (400, 403, 406, 429)
                    if is_blocked:
                        waf_blocked_count += 1

                    canary_probes.append(WAFCanaryProbe(
                        vector=vector,
                        payload=payload,
                        http_status=c_resp.status_code,
                        blocked=is_blocked,
                        waf_vendor=detected_waf,
                        response_signature=f"HTTP {c_resp.status_code}"
                    ))

                    live_hub.record_action(
                        label=f"🛡️ [Canary Testi] {vector}: HTTP {c_resp.status_code} ({'Engellendi ✓' if is_blocked else 'Geçirildi'})",
                        action_type="GATE",
                        target=vector,
                        coords={"x": 600, "y": 160}
                    )
                except Exception:
                    # Timeout or connection drop by WAF is also a block
                    waf_blocked_count += 1
                    canary_probes.append(WAFCanaryProbe(
                        vector=vector,
                        payload=payload,
                        http_status=0,
                        blocked=True,
                        waf_vendor=detected_waf,
                        response_signature="Connection Drop / Timeout"
                    ))

            waf_score = int((waf_blocked_count / len(canaries)) * 100)
            if waf_score >= 75:
                key_strengths.append(f"WAF sentetik enjeksiyon filtreleme başarısı: %{waf_score}")
            else:
                critical_vulnerabilities.append(f"Zararsız enjeksiyon problarında düşük WAF filtreleme oranı: %{waf_score}")

            # ── 2. HAT: HIZ SINIRI (RATE-LIMIT) & BURST DDOS TOLERANSI ──────────
            live_hub.record_action(
                label="⚡ [Hız Sınırı & DDoS] 15 mikro-patlama (burst) isteği ile 429 toleransı ölçülüyor",
                action_type="GATE",
                target="rate_limiter",
                coords={"x": 512, "y": 240}
            )

            burst_count = 15
            burst_reqs = [client.get(target_url, timeout=4.0) for _ in range(burst_count)]
            burst_resps = await asyncio.gather(*burst_reqs, return_exceptions=True)

            statuses = []
            has_429 = False
            for r in burst_resps:
                if isinstance(r, httpx.Response):
                    statuses.append(r.status_code)
                    if r.status_code in (429, 503):
                        has_429 = True

            burst_score = 100 if has_429 else 70
            if has_429:
                key_strengths.append("Hedef sistem ardışık istek patlamasında HTTP 429 Hız Sınırı uyguladı.")
                live_hub.record_action(
                    label="⚡ [Hız Sınırı Doğrulandı] HTTP 429 Too Many Requests savunması devrede ✓",
                    action_type="GATE",
                    target="rate_limiter",
                    coords={"x": 512, "y": 260}
                )
            else:
                live_hub.record_action(
                    label="⚡ [Burst Tamamlandı] 15 istek 429'a takılmadan işlendi (Normal tolerans)",
                    action_type="GATE",
                    target="rate_limiter",
                    coords={"x": 512, "y": 260}
                )

            # ── 3. HAT: AÇIK KAPI & SALDIRI YÜZEYİ RADARI ─────────────────────────
            live_hub.record_action(
                label="🔒 [Açık Kapı Radarı] Hassas dosyalar (.env, .git, dump.sql, yedekler) taranıyor",
                action_type="GATE",
                target="attack_surface",
                coords={"x": 420, "y": 380}
            )

            exposed_count = 0
            for item in CRITICAL_OPEN_DOORS:
                path = item["path"]
                probe_url = urljoin(target_url, path)
                try:
                    p_resp = await client.get(probe_url, timeout=4.0)
                    code = p_resp.status_code
                    text = p_resp.text
                    ct = p_resp.headers.get("content-type", "").lower()
                    is_html = "text/html" in ct or "<html" in text.lower() or "<!doctype" in text.lower()

                    is_exposed = False
                    if code == 200:
                        # Catch-All SPA koruması: HTML dönüyorsa ve validator uyuşmuyorsa açık kapı değildir
                        if not is_html or item["validator"](text):
                            is_exposed = item["validator"](text) if not is_html else item["validator"](text)
                            if ".tar.gz" in path and not is_html:
                                is_exposed = True

                    status_enum = OpenDoorStatus.EXPOSED if is_exposed else (
                        OpenDoorStatus.FILTERED if code in (403, 401) else OpenDoorStatus.SECURE
                    )

                    if is_exposed:
                        exposed_count += 1
                        critical_vulnerabilities.append(f"Kritik Açık Kapı Tespit Edildi: {path} (HTTP 200)")
                        findings.append(Finding(
                            id=f"ETHICAL-EXPOSED-{path.replace('/', '').replace('.', '')}-{int(time.time())}",
                            category=Category.SECURITY,
                            severity=Severity.CRITICAL if item["risk"] == "CRITICAL" else Severity.HIGH,
                            title=f"Kritik Bilgi Sızıntısı: {path} Dosyası Genel Erişime Açık",
                            description=f"Hedef sunucuda {path} adresi kilitli değil. Saldırganlar bu dosyayı indirerek hassas yapılandırma veya veritabanı verilerine erişebilir.",
                            remediation=item["remediation"],
                            rca_category=RCACategory.REAL_BUG,
                            assigned_team="Infra & Security Team"
                        ))

                    open_door_probes.append(OpenDoorProbe(
                        path=path,
                        target_type=item["type"],
                        http_status=code,
                        status=status_enum,
                        response_size_bytes=len(p_resp.content),
                        latency_ms=round(p_resp.elapsed.total_seconds() * 1000, 1),
                        risk_level=item["risk"]
                    ))

                    live_hub.record_action(
                        label=f"🔒 [Açık Kapı] {path} -> HTTP {code} ({'⚠️ AÇIK!' if is_exposed else 'Korumalı ✓'})",
                        action_type="GATE",
                        target=path,
                        coords={"x": 512, "y": 420}
                    )
                except Exception:
                    open_door_probes.append(OpenDoorProbe(
                        path=path,
                        target_type=item["type"],
                        http_status=0,
                        status=OpenDoorStatus.SECURE,
                        risk_level=item["risk"]
                    ))

            open_door_score = max(0, 100 - (exposed_count * 25))
            if exposed_count == 0:
                key_strengths.append(f"Taranan {len(CRITICAL_OPEN_DOORS)} kritik kapının tamamı güvenli şekilde kilitli.")

            # ── 4. BÜTÜNCÜL SİBER DAYANIKLILIK SKORU ($S_{cyber}$) ────────────────
            cyber_score = int(
                (0.35 * waf_score) +
                (0.30 * burst_score) +
                (0.25 * open_door_score) +
                (0.10 * 85) # Header baseline
            )
            cyber_score = max(20, min(100, cyber_score))

            if cyber_score >= 90:
                tier = "FORTRESS"
                verdict = "Kale Düzeyinde Siber Zırh: WAF kalkanı, hız sınırı filtrelemesi ve açık kapı güvenliği kurumsal seviyede."
            elif cyber_score >= 70:
                tier = "RESILIENT"
                verdict = "Dirençli Altyapı: Genel saldırılara karşı korumalı, ancak WAF kurallarının sıkılaştırılması önerilir."
            elif cyber_score >= 50:
                tier = "VULNERABLE"
                verdict = "Savunmasız Noktalar Mevcut: Rate limit veya bazı hassas dizinler saldırgan denemelerine açık."
            else:
                tier = "COMPROMISED"
                verdict = "Kritik Risk: Açık kapı veya veritabanı bilgi sızıntısı riski tespit edildi. Acil müdahale gerektirir."

            report = EthicalSecurityReport(
                target_url=target_url,
                scan_timestamp=datetime.utcnow(),
                cyber_resilience_score=cyber_score,
                resilience_tier=tier,
                waf_detected=bool(detected_waf),
                waf_vendor=detected_waf,
                waf_filtering_score=waf_score,
                burst_ddos_tolerance_score=burst_score,
                burst_requests_sent=burst_count,
                burst_429_received=has_429,
                open_doors_probed=len(open_door_probes),
                open_doors_exposed_count=exposed_count,
                open_doors=open_door_probes,
                canary_probes=canary_probes,
                key_strengths=key_strengths,
                critical_vulnerabilities=critical_vulnerabilities,
                executive_verdict=verdict,
            )

            live_hub.record_action(
                label=f"🛡️ [Beyaz Şapkalı Rapor Hazır] Siber Dayanıklılık Skoru: %{cyber_score} ({tier})",
                action_type="GATE",
                target="cyber_verdict",
                coords={"x": 512, "y": 500}
            )

            return report, findings

        finally:
            if close_client:
                await client.aclose()
