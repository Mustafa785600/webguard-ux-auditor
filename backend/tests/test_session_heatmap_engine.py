import pytest
from app.services.session_heatmap_engine import SessionHeatmapEngine
from app.models.schema import SessionEvent, SessionEventType, Severity

def test_clean_session_without_rage_or_dead_clicks():
    engine = SessionHeatmapEngine()
    # Spaced-out clicks on legitimate buttons and links
    events = [
        SessionEvent(timestamp_ms=500, event_type=SessionEventType.CLICK, x_pct=20.0, y_pct=15.0, selector="a.nav-item", element_text="Ana Sayfa"),
        SessionEvent(timestamp_ms=2500, event_type=SessionEventType.SCROLL, x_pct=50.0, y_pct=30.0, scroll_depth_pct=25.0),
        SessionEvent(timestamp_ms=5000, event_type=SessionEventType.CLICK, x_pct=60.0, y_pct=40.0, selector="button.btn-cta", element_text="İncele"),
        SessionEvent(timestamp_ms=8000, event_type=SessionEventType.SCROLL, x_pct=50.0, y_pct=80.0, scroll_depth_pct=75.0),
        SessionEvent(timestamp_ms=11000, event_type=SessionEventType.CLICK, x_pct=80.0, y_pct=90.0, selector="button#contact-btn", element_text="İletişim"),
    ]

    updated_events, rage_clusters, dead_clicks = engine._detect_rage_and_dead_clicks(events)
    assert len(rage_clusters) == 0
    assert len(dead_clicks) == 0

def test_detect_rage_clicks():
    engine = SessionHeatmapEngine(rage_click_window_ms=800, rage_click_threshold=3)
    # 3 clicks within 400ms at (70.0, 50.0) on button#broken-btn
    events = [
        SessionEvent(timestamp_ms=1000, event_type=SessionEventType.CLICK, x_pct=70.0, y_pct=50.0, selector="button#broken-btn", element_text="Kaydet"),
        SessionEvent(timestamp_ms=1150, event_type=SessionEventType.CLICK, x_pct=70.2, y_pct=50.1, selector="button#broken-btn", element_text="Kaydet"),
        SessionEvent(timestamp_ms=1300, event_type=SessionEventType.CLICK, x_pct=69.9, y_pct=49.8, selector="button#broken-btn", element_text="Kaydet"),
    ]

    report, findings = engine.analyze_or_generate_session("https://example.com")
    # Using our custom events for testing detection directly:
    _, rage_clusters, _ = engine._detect_rage_and_dead_clicks(events)
    assert len(rage_clusters) == 1
    assert rage_clusters[0]["count"] == 3
    assert rage_clusters[0]["selector"] == "button#broken-btn"

    # Verify report generated by default session has findings
    assert report.total_clicks >= 3
    assert report.rage_clicks_count >= 1
    assert any(f.id == "UX_RAGE_CLICK_DETECTED" for f in findings)
    rage_finding = next(f for f in findings if f.id == "UX_RAGE_CLICK_DETECTED")
    assert rage_finding.severity == Severity.MEDIUM
    assert "debouncing" in rage_finding.remediation.lower()

def test_detect_dead_clicks():
    engine = SessionHeatmapEngine()
    # Click on non-interactive div element
    events = [
        SessionEvent(timestamp_ms=1000, event_type=SessionEventType.CLICK, x_pct=30.0, y_pct=40.0, selector="div.static-card-title", element_text="Bilgi Kartı"),
    ]

    _, _, dead_clicks = engine._detect_rage_and_dead_clicks(events)
    assert len(dead_clicks) == 1
    assert dead_clicks[0].selector == "div.static-card-title"

def test_compute_click_hotspots_and_scroll_milestones():
    engine = SessionHeatmapEngine()
    report, _ = engine.analyze_or_generate_session("https://example.com")

    assert len(report.click_hotspots) >= 2
    for h in report.click_hotspots:
        assert 0.0 <= h.x_pct <= 100.0
        assert 0.0 <= h.y_pct <= 100.0
        assert 0.1 <= h.intensity <= 1.0
        assert h.click_count >= 1

    assert len(report.scroll_milestones) == 4
    depths = [m.depth_percentage for m in report.scroll_milestones]
    assert depths == [25, 50, 75, 100]
    assert report.scroll_milestones[0].visitors_reached_pct == 100.0
    assert report.ux_friction_score < 100  # Default simulation contains a rage click

